const fs = require('node:fs'), ts = require('typescript'), assert = require('node:assert/strict');
const moduleOutput = { exports: {} };
new Function('module', 'exports', ts.transpileModule(fs.readFileSync(require('node:path').join(__dirname, '../lib/assistant/typing.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(moduleOutput, moduleOutput.exports);
const { createTypingQueue } = moduleOutput.exports;
(async () => {
  const received = [], abort = new AbortController();
  const queue = createTypingQueue(event => received.push(event), abort.signal);
  const text = 'Bonjour é\n\nFin.';
  queue.push({ type: 'meta', data: { messageId: 'reply' } });
  queue.push({ type: 'text', data: { text } });
  queue.push({ type: 'done', data: {} });
  await new Promise(resolve => setTimeout(resolve, 5));
  assert.ok(received.some(e => e.type === 'text'));
  assert.ok(!received.some(e => e.type === 'done'), 'Completion waits for visible typing');
  await queue.drain();
  assert.equal(received.filter(e => e.type === 'text').map(e => e.data.text).join(''), text);
  assert.equal(received.at(-1).type, 'done');
  const cancelled = new AbortController(), stopped = [];
  const q = createTypingQueue(event => stopped.push(event), cancelled.signal);
  q.push({ type: 'text', data: { text: 'A long response that must stop immediately after cancellation.' } });
  await new Promise(resolve => setTimeout(resolve, 5));
  cancelled.abort(); const count = stopped.length;
  await assert.rejects(q.drain(), { name: 'AbortError' });
  assert.equal(stopped.length, count);
  const instant = [];
  const reduced = createTypingQueue(e => instant.push(e), new AbortController().signal, true);
  reduced.push({ type: 'text', data: { text } }); await reduced.drain();
  assert.equal(instant.length, 1); assert.equal(instant[0].data.text, text);
  console.log('PASS progressive typing: exact text/newlines, event order, stop and reduced motion.');
})().catch(e => { console.error(e); process.exitCode = 1; });
